#!/usr/bin/env node
// Setup and diagnostics for choosing one orchestrator and registering the other agent bridges.
import { spawn } from "node:child_process";
import { accessSync, constants, copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const AGENTS = ["claude", "codex", "opencode", "cursor", "antigravity"];
const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const VERSION = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")).version;
const GUIDE_TEMPLATE = readFileSync(new URL("../templates/orchestrator-guide.md", import.meta.url), "utf8");
const START = "<!-- mcp-agent-bridges:start -->";
const END = "<!-- mcp-agent-bridges:end -->";
const GENERATED = "<!-- generated by mcp-agent-bridges setup -->";
const TOOL_TIMEOUT_SEC = 1800;

const INFO = {
  claude: {
    name: "claude", cli: "claude", tool: "claude_task",
    good: "careful implementation, refactors",
    notes: "edits files; runs only commands in `allow_commands` (exact match); `mode: \"plan\"` is read-only",
  },
  codex: {
    name: "codex-bridge", cli: "codex", tool: "codex_task",
    good: "implementation and follow-ups in the same thread",
    notes: "`sandbox: \"workspace-write\"` (default) or `\"read-only\"`; `effort` sets reasoning effort",
  },
  opencode: {
    name: "opencode", cli: "opencode", tool: "opencode_task",
    good: "volume and mechanical work, often with free models",
    notes: "auto-approves edits and commands by default; `agent: \"plan\"` is read-only",
  },
  cursor: {
    name: "cursor", cli: "cursor-agent", tool: "cursor_task",
    good: "quick, small tasks",
    notes: "`cursor_models` lists models; edits and runs commands by default; `mode: \"plan\"` or `\"ask\"` is read-only",
  },
  antigravity: {
    name: "antigravity", cli: "agy", tool: "antigravity_task",
    good: "backup when others are out of quota",
    notes: "runs no commands except `allow_commands` (exact match); `antigravity_models` lists models; slow",
  },
};

const valid = () => AGENTS.join(", ");
const failAgent = (names) => new Error(`unknown agent${names.length > 1 ? "s" : ""}: ${names.join(", ")}. Valid agents: ${valid()}`);

function selectedExecutors(value, orchestrator) {
  if (!AGENTS.includes(orchestrator)) throw failAgent([orchestrator]);
  if (value === undefined || value === null || value === "") throw new Error("--executors is required");
  if (value === "all") return { executors: AGENTS.filter((a) => a !== orchestrator), skipped: false };
  const requested = (Array.isArray(value) ? value : String(value).split(",")).map((s) => String(s).trim()).filter(Boolean);
  const unknown = requested.filter((a) => !AGENTS.includes(a));
  if (unknown.length) throw failAgent([...new Set(unknown)]);
  const skipped = requested.includes(orchestrator);
  return { executors: [...new Set(requested.filter((a) => a !== orchestrator))], skipped };
}

function resolvedSource(source, root) {
  if (source && source !== "local" && source !== "npx") throw new Error(`invalid source: ${source}. Expected local or npx`);
  return source || (existsSync(join(root, ".git")) ? "local" : "npx");
}

function serverCommand(agent, { source, root = ROOT, version = VERSION, platform = process.platform } = {}) {
  if (!AGENTS.includes(agent)) throw failAgent([agent]);
  const selected = resolvedSource(source, root);
  if (selected === "local") return { command: process.execPath, args: [resolve(root, "packages", `${agent}-bridge`, "server.mjs")] };
  const args = ["-y", `github:ddzendreros/mcp-agent-bridges#v${version}`, agent];
  return platform === "win32" ? { command: "cmd", args: ["/c", "npx", ...args] } : { command: "npx", args };
}

function renderGuide(executors, template = GUIDE_TEMPLATE) {
  const rows = executors.map((agent) => {
    const i = INFO[agent];
    return `| ${agent} | \`${i.tool}\` | ${i.good} | ${i.notes} |`;
  });
  const table = ["| Delegate | Tool | Good for | Notes |", "|---|---|---|---|", ...rows].join("\n");
  return template.replace("{{EXECUTORS}}", table);
}

function upsertSection(existing, content) {
  const block = `${START}\n${String(content).trimEnd()}\n${END}`;
  const marked = /<!-- mcp-agent-bridges:start -->[\s\S]*?<!-- mcp-agent-bridges:end -->/;
  if (marked.test(existing)) return existing.replace(marked, block);
  if (!existing) return block + "\n";
  return `${existing.replace(/\s*$/, "")}\n\n${block}\n`;
}

function setTomlKey(text, table, key, value, file = "config.toml") {
  const escape = (s) => String(s).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const dot = table.lastIndexOf(".");
  const quoted = dot < 0 ? `"${table}"` : `${table.slice(0, dot + 1)}"${table.slice(dot + 1)}"`;
  const header = new RegExp(`^[ \\t]*\\[[ \\t]*(?:${escape(table)}|${escape(quoted)})[ \\t]*\\][ \\t]*(?:#.*)?$`);
  const lines = [];
  const linePattern = /([^\r\n]*)(\r\n|\n|\r|$)/g;
  let match;
  while ((match = linePattern.exec(text)) && (match[0] || match.index < text.length)) {
    lines.push({ content: match[1], eol: match[2] });
    if (!match[2]) break;
  }
  const tableIndex = lines.findIndex((line) => header.test(line.content));
  if (tableIndex < 0) throw new Error(`table [${table}] not found in ${file}: was the server registered?`);
  let end = tableIndex + 1;
  while (end < lines.length && !/^[ \t]*\[/.test(lines[end].content)) end++;
  const assignment = new RegExp(`^([ \\t]*${escape(key)}[ \\t]*=[ \\t]*)(.*)$`);
  for (let i = tableIndex + 1; i < end; i++) {
    const found = assignment.exec(lines[i].content);
    if (!found) continue;
    const comment = found[2].match(/[ \t]*#.*$/);
    const trailing = found[2].match(/[ \t]*$/)[0];
    lines[i].content = `${found[1]}${value}${comment ? comment[0] : trailing}`;
    return lines.map((line) => line.content + line.eol).join("");
  }
  const headerHadEol = Boolean(lines[tableIndex].eol);
  const eol = lines[tableIndex].eol || lines.find((line) => line.eol)?.eol || "\n";
  if (!lines[tableIndex].eol) lines[tableIndex].eol = eol;
  lines.splice(tableIndex + 1, 0, { content: `${key} = ${value}`, eol: tableIndex + 1 < lines.length || headerHadEol ? eol : "" });
  return lines.map((line) => line.content + line.eol).join("");
}

function registrationStep(orchestrator, executor, options) {
  const { command, args } = serverCommand(executor, options);
  const name = INFO[executor].name;
  const label = `Register ${executor} bridge for ${orchestrator}`;
  if (orchestrator === "claude") return { kind: "run", cmd: ["claude", "mcp", "add", "--scope", "user", name, "--", command, ...args], label };
  if (orchestrator === "codex") return { kind: "run", cmd: ["codex", "mcp", "add", name, "--", command, ...args], label };
  if (orchestrator === "opencode") return { kind: "run", cmd: ["opencode", "mcp", "add", "--global", name, "--", command, ...args], label };
  if (orchestrator === "antigravity") return { kind: "run", cmd: ["agy", "mcp", "add", name, "--", command, ...args], label };
  return {
    kind: "json", file: join(options.home, ".cursor", "mcp.json"), key: name,
    value: { command, args }, label,
  };
}

function guideStep(orchestrator, executors, options) {
  const guide = renderGuide(executors, options.template || GUIDE_TEMPLATE);
  if (options.guideFile) return { kind: "section", file: resolve(options.guideFile), content: guide, label: "Write orchestrator guide" };
  if (orchestrator === "cursor") return { kind: "note", text: "Cursor CLI reads AGENTS.md from the project: re-run with --guide-file <project>/AGENTS.md" };
  if (orchestrator === "claude") {
    const file = join(options.home, ".claude", "skills", "delegate-coding-tasks", "SKILL.md");
    if (options.guideExisting !== undefined && !options.guideExisting.includes(GENERATED)) {
      return { kind: "note", text: `Guide already exists at ${file} without the generated marker; merge it by hand or use --guide-file.` };
    }
    const tools = executors.map((a) => INFO[a].tool).join(", ") || "a delegate tool";
    const content = `---\nname: delegate-coding-tasks\ndescription: Use when the user asks to delegate or when a well-defined implementation, refactor, or test task could go to ${tools}.\n---\n${GENERATED}\n\n${guide}`;
    return { kind: "file", file, content, label: "Write orchestrator guide" };
  }
  const file = orchestrator === "codex"
    ? join(options.env.CODEX_HOME || join(options.home, ".codex"), "AGENTS.md")
    : orchestrator === "opencode"
      ? join(options.env.XDG_CONFIG_HOME || join(options.home, ".config"), "opencode", "AGENTS.md")
      : join(options.home, ".gemini", "GEMINI.md");
  return { kind: "section", file, content: guide, label: "Write orchestrator guide" };
}

function plan(opts = {}) {
  if (!opts.orchestrator) throw new Error("--orchestrator is required");
  const orchestrator = String(opts.orchestrator).trim();
  const { executors, skipped } = selectedExecutors(opts.executors, orchestrator);
  const root = resolve(opts.root || ROOT), home = resolve(opts.home || homedir());
  const source = resolvedSource(opts.source, root);
  const options = {
    source, root, home, version: opts.version || VERSION, platform: opts.platform || process.platform,
    env: opts.env || process.env, guideFile: opts.guideFile, guideExisting: opts.guideExisting, template: opts.template,
  };
  const steps = [];
  if (skipped) steps.push({ kind: "note", text: `${orchestrator} is the orchestrator, so it was skipped as an executor.` });
  for (const executor of executors) {
    steps.push(registrationStep(orchestrator, executor, options));
    if (orchestrator === "codex") {
      steps.push({
        kind: "toml", file: join(options.env.CODEX_HOME || join(home, ".codex"), "config.toml"),
        table: `mcp_servers.${INFO[executor].name}`, key: "tool_timeout_sec", value: TOOL_TIMEOUT_SEC,
        label: `Set ${executor} bridge tool timeout for codex`,
      });
    }
  }
  if (!opts.noGuide) steps.push(guideStep(orchestrator, executors, options));
  return steps;
}

function isFile(path) {
  try { return statSync(path).isFile(); } catch { return false; }
}

function executableOnPath(command, { env = process.env, platform = process.platform } = {}) {
  const path = env.PATH || env.Path || env.path || "";
  const dirs = path.split(platform === "win32" ? ";" : ":").filter(Boolean);
  const hasExt = /\.[^\\/.]+$/.test(command);
  const exts = platform === "win32"
    ? (hasExt ? [""] : (env.PATHEXT || ".COM;.EXE;.BAT;.CMD").split(";"))
    : [""];
  for (const dir of dirs) {
    for (const ext of exts) {
      const file = join(dir, command + ext);
      if (!isFile(file)) continue;
      if (platform === "win32") return file;
      try { accessSync(file, constants.X_OK); return file; } catch { /* keep looking */ }
    }
  }
  return null;
}

function knownPaths(agent, { home = homedir(), env = process.env, platform = process.platform } = {}) {
  if (agent === "claude") return [
    platform === "win32" ? join(home, ".local", "bin", "claude.exe") : null,
    join(home, ".local", "bin", "claude"),
  ].filter(Boolean);
  if (agent === "codex") return [platform === "win32" && env.APPDATA ? join(env.APPDATA, "npm", "codex.cmd") : null].filter(Boolean);
  if (agent === "opencode") return [platform === "win32" && env.APPDATA ? join(env.APPDATA, "npm", "opencode.cmd") : null].filter(Boolean);
  if (agent === "cursor") return [
    platform === "win32" && env.LOCALAPPDATA ? join(env.LOCALAPPDATA, "cursor-agent", "cursor-agent.cmd") : null,
    join(home, ".local", "bin", "cursor-agent"),
  ].filter(Boolean);
  return [
    platform === "win32" && env.LOCALAPPDATA ? join(env.LOCALAPPDATA, "agy", "bin", "agy.exe") : null,
    join(home, ".local", "bin", "agy"),
  ].filter(Boolean);
}

function locateCLI(agent, options = {}) {
  const found = executableOnPath(INFO[agent].cli, options);
  if (found) return found;
  return knownPaths(agent, options).find((p) => isFile(p)) || null;
}

function quoteWindows(s) {
  return /[\s"&|<>^%!()]/.test(s) ? `"${String(s).replace(/"/g, '""')}"` : s;
}

function displayCommand(cmd, platform) {
  if (platform === "win32") return cmd.map(quoteWindows).join(" ");
  return cmd.map((s) => (/^[A-Za-z0-9_./:=@#-]+$/.test(s) ? s : `'${String(s).replace(/'/g, `'"'"'`)}'`)).join(" ");
}

function spawnCapture(command, args, { shell = false, timeoutMs = 120000 } = {}) {
  return new Promise((resolveResult) => {
    let child;
    try { child = spawn(command, args, { shell, windowsHide: true, stdio: ["ignore", "pipe", "pipe"] }); }
    catch (error) { return resolveResult({ code: -1, out: "", err: String(error), error }); }
    let out = "", err = "", timedOut = false, settled = false, grace;
    child.stdout.on("data", (d) => (out += d));
    child.stderr.on("data", (d) => (err += d));
    const finish = (code, error) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      clearTimeout(grace);
      child.stdout?.destroy();
      child.stderr?.destroy();
      resolveResult({ code, out, err, timedOut, error });
    };
    const timer = setTimeout(() => {
      timedOut = true;
      try { child.kill(); } catch { /* gone */ }
      grace = setTimeout(() => finish(child.exitCode), 1000);
    }, timeoutMs);
    child.on("error", (error) => finish(-1, error));
    child.on("close", (code) => finish(code));
  });
}

function timestamp(date = new Date()) {
  return date.toISOString().replace(/[-:T]/g, "").slice(0, 14);
}

function backup(file) {
  let time = Date.now(), target;
  do { target = `${file}.bak-${timestamp(new Date(time))}`; time += 1000; } while (existsSync(target));
  copyFileSync(file, target);
  return target;
}

function writeChanged(file, content) {
  const exists = existsSync(file);
  const current = exists ? readFileSync(file, "utf8") : "";
  if (current === content) return false;
  if (exists) backup(file);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  return true;
}

async function applyRun(step, options) {
  const agent = Object.keys(INFO).find((a) => INFO[a].cli === step.cmd[0]);
  const found = agent ? locateCLI(agent, options) : executableOnPath(step.cmd[0], options);
  if (!found) return { ok: false, detail: `not found: ${step.cmd[0]}` };
  let command = found, args = step.cmd.slice(1), shell = false;
  if (options.platform === "win32") {
    command = [found, ...args].map(quoteWindows).join(" ");
    args = [];
    shell = true;
  }
  const r = await spawnCapture(command, args, { shell });
  if (r.code === 0 && !r.timedOut) return { ok: true };
  const tail = (r.err || r.out || String(r.error || "failed")).trim().slice(-300);
  return { ok: false, detail: r.timedOut ? "timed out" : tail || `exit ${r.code}` };
}

function applyJSON(step) {
  let data = {};
  if (existsSync(step.file)) data = JSON.parse(readFileSync(step.file, "utf8"));
  if (!data || typeof data !== "object" || Array.isArray(data)) throw new Error("existing JSON root is not an object");
  if (!data.mcpServers || typeof data.mcpServers !== "object" || Array.isArray(data.mcpServers)) data.mcpServers = {};
  data.mcpServers[step.key] = step.value;
  const content = JSON.stringify(data, null, 2) + "\n";
  writeChanged(step.file, content);
}

function applyTOML(step) {
  if (!existsSync(step.file)) throw new Error(`table [${step.table}] not found in ${step.file}: was the server registered?`);
  const content = setTomlKey(readFileSync(step.file, "utf8"), step.table, step.key, step.value, step.file);
  writeChanged(step.file, content);
}

async function applySteps(steps, options) {
  let failed = false;
  for (const step of steps) {
    if (step.kind === "note") { process.stdout.write(`note: ${step.text}\n`); continue; }
    try {
      if (step.kind === "run") {
        const r = await applyRun(step, options);
        if (!r.ok) throw new Error(r.detail);
      } else if (step.kind === "json") applyJSON(step);
      else if (step.kind === "toml") applyTOML(step);
      else if (step.kind === "section") {
        const existing = existsSync(step.file) ? readFileSync(step.file, "utf8") : "";
        writeChanged(step.file, upsertSection(existing, step.content));
      } else if (step.kind === "file") writeChanged(step.file, step.content.endsWith("\n") ? step.content : step.content + "\n");
      process.stdout.write(`✓ ${step.label}\n`);
    } catch (error) {
      failed = true;
      process.stdout.write(`✗ ${step.label}: ${String(error?.message || error)}\n`);
    }
  }
  return failed ? 1 : 0;
}

function printDryRun(orchestrator, executors, source, steps, options) {
  process.stdout.write(`Orchestrator: ${orchestrator}   Executors: ${executors.join(",")}   Source: ${source}\n`);
  steps.forEach((step, i) => {
    let text;
    if (step.kind === "run") text = displayCommand(step.cmd, options.platform);
    else if (step.kind === "json") text = `update ${step.file}: mcpServers.${step.key} = ${JSON.stringify(step.value)}`;
    else if (step.kind === "toml") text = `update ${step.file}: [${step.table}] ${step.key} = ${step.value}`;
    else if (step.kind === "section" || step.kind === "file") text = `write guide → ${step.file}`;
    else text = `note: ${step.text}`;
    process.stdout.write(`${i + 1}. ${text}\n`);
  });
  const needed = new Set();
  if (orchestrator !== "cursor") needed.add(orchestrator);
  for (const executor of executors) needed.add(executor);
  for (const agent of needed) {
    if (!locateCLI(agent, options)) process.stdout.write(`warning: ${INFO[agent].cli} not found on PATH (needed by ${agent})\n`);
  }
  process.stdout.write("Dry run: nothing was changed. Re-run with --write to apply.\n");
}

function parseSetupArgs(argv) {
  const opts = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--write") opts.write = true;
    else if (arg === "--no-guide") opts.noGuide = true;
    else if (arg === "--orchestrator" || arg === "--executors" || arg === "--source" || arg === "--guide-file" || arg === "--home") {
      if (argv[i + 1] === undefined || argv[i + 1].startsWith("--")) throw new Error(`${arg} requires a value`);
      const key = { "--orchestrator": "orchestrator", "--executors": "executors", "--source": "source", "--guide-file": "guideFile", "--home": "home" }[arg];
      opts[key] = argv[++i];
    } else throw new Error(`unknown setup option: ${arg}`);
  }
  if (!opts.orchestrator) throw new Error("--orchestrator is required");
  if (!opts.executors) throw new Error("--executors is required");
  return opts;
}

async function setupMain(argv) {
  let opts;
  try { opts = parseSetupArgs(argv); }
  catch (error) { process.stderr.write(`error: ${error.message}\nValid agents: ${valid()}\n`); return 2; }
  const root = ROOT, home = resolve(opts.home || homedir()), platform = process.platform, env = process.env;
  let selection, source, steps;
  try {
    selection = selectedExecutors(opts.executors, opts.orchestrator);
    source = resolvedSource(opts.source, root);
    const planOpts = { ...opts, root, home, platform, env, version: VERSION, source };
    if (!opts.noGuide && !opts.guideFile && opts.orchestrator === "claude") {
      const file = join(home, ".claude", "skills", "delegate-coding-tasks", "SKILL.md");
      if (existsSync(file)) planOpts.guideExisting = readFileSync(file, "utf8");
    }
    steps = plan(planOpts);
  } catch (error) {
    process.stderr.write(`error: ${error.message}\n`);
    return 2;
  }
  const runtime = { home, env, platform };
  if (!opts.write) { printDryRun(opts.orchestrator, selection.executors, source, steps, runtime); return 0; }
  process.stdout.write(`Orchestrator: ${opts.orchestrator}   Executors: ${selection.executors.join(",")}   Source: ${source}\n`);
  return applySteps(steps, runtime);
}

async function doctor() {
  process.stdout.write(`✓ node      ${process.version} (${process.execPath})\n`);
  const options = { home: homedir(), env: process.env, platform: process.platform };
  const results = await Promise.all(AGENTS.map(async (agent) => {
    const file = locateCLI(agent, options);
    if (!file) return { agent, ok: false, text: "not found" };
    const shell = process.platform === "win32" && /\.(?:cmd|bat)$/i.test(file);
    const command = shell ? `${quoteWindows(file)} --version` : file;
    const r = await spawnCapture(command, shell ? [] : ["--version"], { shell, timeoutMs: 15000 });
    const text = (r.out || r.err).trim().split(/\r?\n/).find(Boolean) || `exit ${r.code}`;
    return { agent, ok: r.code === 0 && !r.timedOut, text: r.timedOut ? "timed out" : text, file };
  }));
  for (const r of results) {
    const name = r.agent.length >= 10 ? r.agent + " " : r.agent.padEnd(10);
    process.stdout.write(`${r.ok ? "✓" : "✗"} ${name}${r.text}${r.file ? ` (${r.file})` : ""}\n`);
  }
  return 0;
}

export { AGENTS, TOOL_TIMEOUT_SEC, doctor, locateCLI, plan, renderGuide, serverCommand, setTomlKey, setupMain, upsertSection };
